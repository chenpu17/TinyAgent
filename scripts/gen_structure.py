#!/usr/bin/env python3
"""Generate the README 代码结构 tree from the actual source files.

Line counts are read live from disk so they can never drift (the hand-written
table was off by 2–5x and missing whole modules); the one-line descriptions
live in ENTRIES below — update a module's row where you change its role.

  python3 scripts/gen_structure.py --write   # regenerate the README block
  python3 scripts/gen_structure.py --check   # CI gate: non-zero on drift
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
BEGIN = "<!-- BEGIN CODE STRUCTURE (generated by scripts/gen_structure.py) -->"
END = "<!-- END CODE STRUCTURE -->"

