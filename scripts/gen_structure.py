def line_count(path: Path) -> int:
    with path.open("rb") as f:
        return sum(1 for _ in f)


def render_crate(crate_root: str, crate_note: str, entries, name_w: int) -> list:
    """One crate's subtree: a root line, then files/dirs in ENTRIES order."""
    lines = [f"{crate_root}/  # {crate_note}"]
    # Top-level order with directory grouping preserved from this crate's
    # ENTRIES slice: kind = "file" | "dir". Entries three parts deep (e.g.
    # tools/run_code/contract.rs) render as a nested subdirectory block
    # after that directory's flat files, in ENTRIES first-appearance order.
    top, children, nested = [], {}, {}
    for _root, path, desc in entries:
        p = Path(path)
        if len(p.parts) == 1:
            top.append(("file", p.parts[0], desc))
            continue
        if p.parts[0] not in [key for kind, key, _ in top if kind == "dir"]:
            top.append(("dir", p.parts[0], None))
        if len(p.parts) == 2:
            children.setdefault(p.parts[0], []).append((p.parts[1], desc))
        else:
            nested.setdefault(p.parts[0], {}).setdefault(p.parts[1], []).append(
                (p.parts[2], desc)
            )
    for i, (kind, key, desc) in enumerate(top):
        last = i == len(top) - 1
        conn, ext = ("└── ", "    ") if last else ("├── ", "│   ")
        if kind == "dir":
            note = f"  # {DIR_COMMENTS[key]}" if key in DIR_COMMENTS else ""
            lines.append(f"{conn}{key}/{note}")
            flat = children.get(key, [])
            subs = list(nested.get(key, {}).items())
            total = len(flat) + len(subs)
            pos = 0
            for name, d in flat:
                pos += 1
                clast = pos == total
                cconn = "└── " if clast else "├── "
                count = line_count(ROOT / crate_root / key / name)
                lines.append(f"{ext}{cconn}{name:<{name_w}}({count:>5})  # {d}")
            for sub, sub_entries in subs:
                pos += 1
                clast = pos == total
                cconn = "└── " if clast else "├── "
                snote_key = f"{key}/{sub}"
                snote = f"  # {DIR_COMMENTS[snote_key]}" if snote_key in DIR_COMMENTS else ""
                lines.append(f"{ext}{cconn}{sub}/{snote}")
                sext = "    " if clast else "│   "
                for k, (name, d) in enumerate(sub_entries):
                    slast = k == len(sub_entries) - 1
                    sconn = "└── " if slast else "├── "
                    count = line_count(ROOT / crate_root / key / sub / name)
                    lines.append(f"{ext}{sext}{sconn}{name:<{name_w}}({count:>5})  # {d}")
        else:
            count = line_count(ROOT / crate_root / key)
            lines.append(f"{conn}{key:<{name_w}}({count:>5})  # {desc}")
    return lines


def build_tree() -> str:
    name_w = max(len(e[1].split("/")[-1]) for e in ENTRIES) + 1
    lines = []
    for ci, (crate_root, note) in enumerate(CRATES):
        entries = [e for e in ENTRIES if e[0] == crate_root]
        subtree = render_crate(crate_root, note, entries, name_w)
        lines.extend(subtree if ci == 0 else ["", *subtree])
    return "\n".join(lines)


def expected_block() -> str:
    return f"{BEGIN}\n```text\n{build_tree()}\n```\n{END}"


def check_reverse_integrity() -> None:
    """The mirror of the existence check: every .rs file under a tracked
    crate root must be listed in ENTRIES — a new module that misses the
    list would silently vanish from the README tree and this gate could
    never notice (both key on the explicit list). Descriptions are
    human-written, so a miss FAILS with the file list instead of the tree
    auto-growing a blank row. Runs in BOTH --check and --write modes."""
    listed = {f"{root}/{path}" for root, path, _ in ENTRIES}
    missing = []
    for crate_root, _note in CRATES:
        for f in sorted((ROOT / crate_root).rglob("*.rs")):
            rel = f"{crate_root}/{f.relative_to(ROOT / crate_root).as_posix()}"
            if rel not in listed:
                missing.append(rel)
    if missing:
        raise SystemExit(
            "gen_structure: .rs files present on disk but missing from "
            "ENTRIES (they would silently drop out of the README tree) —\n"
            "add a row with a one-line description for each:\n  "
            + "\n  ".join(missing)
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()

    # Every entry must exist — a typo'd path would silently drop a module
    # from the tree instead of failing.
    for crate_root, path, _ in ENTRIES:
        if not (ROOT / crate_root / path).is_file():
            raise SystemExit(f"gen_structure: {crate_root}/{path} does not exist (fix ENTRIES)")
    # And every module on disk must have an entry (the reverse direction).
    check_reverse_integrity()

    for readme in READMES:
        current = readme.read_text(encoding="utf-8")
        if BEGIN not in current or END not in current:
            raise SystemExit(
                f"gen_structure: {readme.name} markers missing — re-add the BEGIN/END block"
            )
        head, rest = current.split(BEGIN, 1)
        _, tail = rest.split(END, 1)

        # Keep everything before BEGIN, regenerate the middle, keep after END.
        candidate = head + BEGIN + f"\n```text\n{build_tree()}\n```\n" + END + tail

        if args.write:
            if candidate != current:
                # newline="\n" keeps the README byte-identical across platforms
                # (text-mode default would write CRLF on Windows — same
                # discipline as sync_run_code_contract.py's --write).
                readme.write_text(candidate, encoding="utf-8", newline="\n")
                print(f"gen_structure: {readme.name} tree regenerated.")
            else:
                print(f"gen_structure: {readme.name} already up to date.")
        else:
            if candidate != current:
                raise SystemExit(
                    f"{readme.name} structure tree is stale; run scripts/gen_structure.py --write"
                )
            print(f"gen_structure: {readme.name} tree up to date.")


if __name__ == "__main__":
    main()
