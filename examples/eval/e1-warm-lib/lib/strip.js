function taStripCore(body) {
  const parts = body.split("。").map(s => s.trim()).filter(Boolean);
  const keep = parts.filter(s => !TA_BP.some(r => r.test(s)));
  const out = [];
  for (const s of keep) { if (out[out.length - 1] !== s) out.push(s); }
  return out.join("。");
}
